#!/bin/sh
# Настройка и запуск зеркала баз ClamAV.
#
# `cvd serve` совмещает раздачу и обновление по расписанию: отдельный планировщик
# не нужен, а лишний процесс — лишний повод для рассинхрона.
set -eu

DB_DIR="${CVD_DB_DIR:-/db}"
PORT="${CVD_PORT:-8000}"
INTERVAL="${CVD_UPDATE_INTERVAL_S:-14400}"
NAMESERVER="${CVD_NAMESERVER:-1.1.1.1}"

# Резолвер задаётся явно. cvdupdate сам спрашивает TXT-запись, чтобы понять,
# нужно ли качать: это дешёвая проверка, ради которой CDN и просит не ходить
# полными файлами. Там, где системный DNS подменяют, ответ приходит битым —
# в логах freshclam это «Invalid DNS reply», а следом бан за частые скачивания.
cvd config set --dbdir "$DB_DIR" --nameserver "$NAMESERVER"

echo "зеркало баз: каталог $DB_DIR, порт $PORT, обновление раз в ${INTERVAL} с, резолвер $NAMESERVER"

# Первое обновление отдельно и без падения: если наружу сейчас не пройти,
# раздавать всё равно есть что — clamd возьмёт базу из своего образа.
# При неудаче — причина, а не только факт: `cvdupdate` пишет «Failed to
# download» без объяснения, а закрытый CDN, отсутствие выхода и лимит частоты
# чинятся разными людьми.
if ! cvd update; then
	echo "первое обновление не удалось, раздаём что есть"
	python3 /usr/local/bin/probe.py || true
fi

# Экспортёр метрик поднимается рядом и следит за каталогом со стороны.
# Отдельным процессом, потому что раздача важнее метрик: его падение не должно
# трогать `cvd serve`, а `cvd serve` остаётся первым в списке аргументов exec.
python3 /usr/local/bin/exporter.py &

exec cvd serve "$PORT" --update-interval-seconds "$INTERVAL"
