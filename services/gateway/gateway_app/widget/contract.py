"""Публичный контракт виджета (M12.8).

Раздаём скрипт мы, ломаем тоже мы, а у сайта нет способа откатиться: он
подключил `<script src=...>` и получает то, что мы отдали сегодня. Это делает
совместимость не пожеланием, а условием.

Отсюда правило: **совместимые изменения едут на том же адресе, несовместимые —
только на новом.** Версия стоит в пути (`/widget/v1/...`), а не в параметре
запроса: адрес — то единственное, что сайт у себя записал, и менять поведение
за одним и тем же адресом значит менять то, что он не менял.

Здесь перечислено то, что нельзя тронуть, не сменив версию. Список существует
затем, чтобы ломающее изменение упиралось в упавший тест, а не обнаруживалось
на чужих страницах.
"""

from __future__ import annotations

from typing import Final

VERSION: Final = "v1"
"""Версия контракта. Совпадает с префиксом пути и отдаётся заголовком."""

MESSAGE_TYPES: Final = frozenset(
    {
        "ready",  # фрейм загрузился и готов принять файл
        "busy",  # файл выбран, идёт проверка
        "checked",  # проверка завершена, есть scan_id
        "pending",  # не успели в отведённое время, есть scan_id
        "blocked",  # вердикт `malicious`, файл к отправке не годится
        "unchecked",  # проверка не состоялась — это НЕ «чисто»
    }
)
"""Что фрейм сообщает странице.

Добавить тип — совместимо: страница, которая его не знает, просто не среагирует.
Убрать или переименовать — ломающее: обработчик на стороне сайта перестанет
срабатывать, и молча.
"""

TYPES_WITH_SCAN_ID: Final = frozenset({"checked", "pending"})
"""Сообщения, при которых скрытое поле заполняется.

Всё остальное его очищает. Пустое значение на сервере сайта означает «вложения
нет» — безопасное состояние: непроверенный файл не должен выглядеть как
проверенный.
"""

DEFAULT_FIELD: Final = "vulnscan_scan_id"
"""Имя скрытого поля по умолчанию. Переопределяется `data-vulnscan-field`."""

STATE_FIELD: Final = "vulnscan_state"
"""Второе скрытое поле: тип последнего сообщения (M12.9).

Пустой `scan_id` означает «вложения нет», но не объясняет почему: посетитель не
прикладывал файл, файл заблокирован или проверка не состоялась — снаружи это
одно и то же. Бэкенду сайта разница важна, и явное состояние честнее, чем
догадка по пустому полю.

Поле добавлено в `v1` без смены версии сознательно: добавление необязательного
поля совместимо — сайт, который его не читает, ничего не замечает.
"""

HOST_ATTRIBUTE: Final = "data-vulnscan-key"
"""Атрибут, по которому загрузчик находит место для виджета."""

UNAVAILABLE_MODES: Final = ("block", "mark")
"""Что виджет делает с непроверенным файлом. Задаётся политикой тенанта."""

STATUS_TICKET_HEADER: Final = "X-Vulnscan-Status-Ticket"
"""Заголовок с талоном наблюдения в ответе на отложенную загрузку.

Заголовком, а не полем ответа: `ScanResult` — публичная модель для всех
способов подключения, и класть в неё то, что нужно одному из них, значит
менять общий контракт ради частного случая.
"""

FRAME_PARAMS: Final = ("key", "origin")
"""Параметры документа фрейма. Их формирует загрузчик, но переносить фрейм
руками тоже возможно — значит это тоже контракт.
"""
