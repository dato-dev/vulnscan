"""Оформление фрейма: закрытый список переменных CSS.

Команды хотят вписать виджет в свой дизайн, и это законно: чужая кнопка
посреди формы выглядит чужой. Вопрос только в том, **как** давать эту
возможность.

Принимать чужой CSS нельзя. Стили внутри нашего документа — это чужой код на
нашем origin: `background-image: url(...)` умеет обращаться наружу и уносить
с собой факт открытия формы, селекторы достают до всего, что мы показываем, а
`content` умеет дописывать текст к нашим сообщениям — включая «файл проверен».

Поэтому список закрытый: имя переменной должно быть известно заранее, а
значение — пройти проверку. Что не подошло, отбрасывается молча: подсказка
«такая переменная не поддерживается» здесь никому не поможет, а подбирать по
ответу поможет.
"""

from __future__ import annotations

import re
from typing import Final

_COLOR = re.compile(r"^#[0-9a-f]{3,8}$|^[a-z]{3,20}$|^rgba?\([\d\s.,%]{3,40}\)$", re.I)
_LENGTH = re.compile(r"^\d{1,3}(\.\d{1,2})?(px|rem|em|%)$")
_FONT = re.compile(r'^[\w\s,\'"-]{1,120}$')

ALLOWED: Final = {
    # параметр адреса: (переменная CSS, чем проверяется значение)
    "font": ("--vs-font", _FONT),
    "size": ("--vs-size", _LENGTH),
    "color": ("--vs-color", _COLOR),
    "accent": ("--vs-accent", _COLOR),
    "radius": ("--vs-radius", _LENGTH),
    "gap": ("--vs-gap", _LENGTH),
    "error": ("--vs-error", _COLOR),
    "warn": ("--vs-warn", _COLOR),
    "ok": ("--vs-ok", _COLOR),
}
"""Что сайт вправе переопределить: имя, переменная, проверка значения.

Одна таблица, а не две. Раньше имена и проверки лежали раздельно, и охраняли
на самом деле только проверки: имя без правила отбрасывалось, а правило без
имени было недостижимо. Разъехавшись, такие списки не ломаются заметно —
переменная просто перестаёт действовать.

Короткие имена наружу, чтобы адрес фрейма оставался читаемым, и наши внутри,
чтобы переименование переменной не ломало чужую разметку.
"""

VARIABLES: Final = {name: variable for name, (variable, _rule) in ALLOWED.items()}
"""Имя параметра → переменная CSS. Для тех, кому нужны только имена."""


def build(params: dict[str, str]) -> str:
    """Собирает блок стилей из параметров запроса.

    Возвращает готовое содержимое `<style>` — пустое, если ничего годного не
    передали. Значения проходят через регулярные выражения, а не экранируются:
    экранирование защищает от выхода из строки, а нам нужно защититься от
    **любого** значения, которого мы не ожидали. Проверка списком разрешённого
    отвечает на второй вопрос, экранирование — только на первый.
    """
    declarations = []
    for name, value in params.items():
        allowed = ALLOWED.get(name)
        if allowed is None:
            continue
        variable, rule = allowed

        candidate = value.strip()
        if not candidate or not rule.fullmatch(candidate):
            continue

        declarations.append(f"  {variable}: {candidate};")

    if not declarations:
        return ""

    body = "\n".join(declarations)
    return f":root {{\n{body}\n}}"
