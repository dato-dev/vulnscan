"""Версия сборки: одно место, откуда её берут логи, трассировка и `/readyz`.

Зачем это отдельным модулем. Вопрос «какая версия сейчас работает» возникает
ровно в тот момент, когда что-то сломалось, и ответ на него нужен быстрее
всего. Раньше его приходилось выводить косвенно: посмотреть тег образа в
compose, вспомнить, выкатывали ли его, сверить с тем, что в git. Каждый шаг —
возможность ошибиться, а ошибка тут стоит часа поисков не в том коде.

Версия складывается из двух разных вещей, и путать их нельзя.

`VERSION` — версия исходников из `pyproject.toml`. Меняется руками, когда
меняется контракт, и одинакова у всех сервисов: они собираются из одного
дерева.

`IMAGE_TAG` — то, чем помечен образ при сборке. Это и есть ответ на вопрос
«что выкатано». Приходит переменной окружения, потому что раньше сборки его не
существует.

Расходятся они постоянно и законно: один и тот же исходник уезжает под тегами
`v1.2.0` и `latest`. Поэтому в лог идут оба.
"""

from __future__ import annotations

import os
from typing import Final

try:
    from importlib.metadata import PackageNotFoundError
    from importlib.metadata import version as _package_version

    VERSION: Final = _package_version("vulnscantg")
except (ImportError, PackageNotFoundError):  # pragma: no cover — путь для образа
    # В образе пакет не устанавливается: код копируется каталогами, метаданных
    # нет. Это не деградация — просто другой способ доставки, и придумывать
    # ради него установку пакета незачем.
    VERSION = "0.1.0"

UNKNOWN: Final = "unknown"
"""Что пишем, когда тег не задан.

Пустая строка выглядела бы как «версии нет», а `unknown` — как «нам её не
сказали». Разница существенна: во втором случае чинить надо выкат, а не код.
"""


def image_tag() -> str:
    """Тег образа. Задаётся при выкате, в коде его знать неоткуда."""
    return os.environ.get("IMAGE_TAG", "").strip() or UNKNOWN


def build_info() -> dict[str, str]:
    """Что писать в лог при старте и отдавать в `/readyz`.

    Имени сервиса здесь нет: его подставляет форматтер логов в каждую запись,
    и дублировать значит однажды получить две разные версии одного поля.
    """
    return {"version": VERSION, "image_tag": image_tag()}
