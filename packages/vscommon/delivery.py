"""Куда уезжает обезвреженная копия (M14).

Разделение здесь одно и оно несущее: **адрес — это политика, учётные данные —
секрет**, и лежат они в разных местах.

Адрес приёмника описан в `policies.json` рядом с порогами. Этот файл читают
gateway, воркер и deepscan — то есть в том числе процесс, который разбирает
враждебные файлы. Знание «мы пишем в такой-то бакет» ему безвредно.

Учётные данные там лежать не могут по той же причине: ключ доступа к чужому
хранилищу в файле, доступном воркеру, означает, что дыра в парсере даёт запись
в инфраструктуру клиента. Поэтому в политике стоит **ссылка** —
`credentials_id`, — а сами ключи разрешает notifier из своего файла, воркеру
не видного. Полный доступ к политикам после этого даёт знание, куда мы пишем,
но не возможность туда написать.

Второе решение — строгость разбора. `TenantPolicy` неизвестные поля
игнорирует, и это правильно: так клиент не подсунет себе `on_timeout:
fail-open`. Но для приёмника мягкость означала бы, что опечатка в имени поля
превращается в «доставка не настроена», а дальше файлы просто не появляются в
ящике. Поэтому блок `delivery` разбирается с `extra="forbid"`, а неудача
разбора — это состояние «настроена и сломана», отличное от «не настроена».
Различать их обязательно: первое чинят, второе — нормальная работа.
"""

from __future__ import annotations

import json
import logging
import re
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

logger = logging.getLogger(__name__)

MIN_SECRET_LEN = 16
"""Ключ короче этого не принимается: чужое хранилище — не место для опечатки."""


class Delivery(BaseModel):
    """Приёмник обезвреженных копий. Задаётся политикой, не запросом.

    Клиент не может назвать приёмник в запросе, и это не удобство, а защита:
    «просканируй и положи вот сюда» — готовый примитив записи куда угодно и
    канал вывода данных наружу. Ровно тот же довод, по которому адреса
    коллбэков проверяются по списку ключа (`vscommon/callbacks.py`).
    """

    model_config = ConfigDict(extra="forbid")

    backend: Literal["s3"] = "s3"
    """Пока только S3. SMB — отдельным решением (M14.6), NFS — не в нашем
    периметре (M14.7): это монтирование, а не клиент."""

    endpoint: str = ""
    """Адрес хранилища. Пусто — тот же, что у нашего S3 (для стенда)."""

    bucket: str = Field(min_length=1)
    prefix: str = ""
    """Префикс ключа. Свой на тенанта — так компрометация одной учётки не даёт
    писать в чужие каталоги (M14.4)."""

    region: str = ""

    credentials_id: str = Field(min_length=1)
    """Ссылка на учётные данные, а не сами данные. См. модуль целиком."""

    key_template: str = "{date}/{scan_id}{ext}"
    """Как называть объект. Подстановки только из закрытого списка `TOKENS`.

    Умолчание группирует по дню: `2026/09/07/04cb0ab5….pdf`. Без даты в ящике
    лежит плоская груда случайных имён — её нельзя ни отсортировать, ни
    посмотреть за период, ни разделить при выгрузке.

    Список закрытый по той же причине, что и переменные оформления виджета:
    открытый шаблон над результатом рано или поздно получил бы `{filename}`, и
    персональные данные уехали бы в **ключ объекта** — то есть в логи доступа
    хранилища, где живут дольше самого файла.
    """

    @property
    def needs_filename(self) -> bool:
        """Нужно ли доносить имя файла до воркера.

        Спрашивает gateway. Имя пойдёт через очередь и осядет в Redis, поэтому
        несём его только когда шаблон действительно просит: включённое «на
        всякий случай» хранение персональных данных так и остаётся навсегда.
        """
        return "{filename}" in self.key_template

    def object_name(
        self,
        scan_id: str,
        sha256: str,
        verdict: str,
        ext: str,
        when: float,
        filename: str = "",
    ) -> str:
        """Имя объекта по шаблону. Дата — момент проверки, а не выгрузки.

        Иначе повтор доставки через сутки положил бы файл в каталог другого
        дня, и объём за период перестал бы сходиться с историей проверок.
        """
        moment = datetime.fromtimestamp(when, tz=UTC)
        rendered = self.key_template.format(
            date=moment.strftime("%Y/%m/%d"),
            year=moment.strftime("%Y"),
            month=moment.strftime("%m"),
            day=moment.strftime("%d"),
            scan_id=scan_id,
            sha=sha256[:12],
            verdict=verdict,
            ext=ext,
            # Единственное значение, пришедшее от пользователя. Запасное —
            # `scan_id`: он уникален, и подстановка пустоты дала бы пустой
            # сегмент ключа, то есть остановку доставки на одном кривом имени.
            filename=safe_filename(filename, scan_id),
        )
        return _safe_key(rendered)

    def key_for(self, name: str) -> str:
        """Полный ключ объекта в приёмнике.

        Разделитель добавляется здесь, а не в настройке: префикс без косой
        черты — обычная опечатка, и её последствие (`vulnscanfile.pdf` вместо
        `vulnscan/file.pdf`) выглядит как работающая доставка не туда.
        """
        prefix = self.prefix.strip("/")
        return f"{prefix}/{name}" if prefix else name


REBUILT_PREFIX = "_rebuilt/"
"""Куда кладутся копии, пересобранные из ЗАБЛОКИРОВАННЫХ файлов (M14.9).

Константа, а не настройка, и не подстановка в шаблоне. Разделение не должно
зависеть от того, вспомнил ли оператор дописать `{verdict}` в `key_template`:
скрипт на стороне клиента обрабатывает каталог целиком и манифест у каждого
файла не читает. Оказавшись в общем каталоге, такой документ был бы принят за
обычный — а он пересобран из файла, в котором мы нашли вредоносное.
"""

TOKENS = ("date", "year", "month", "day", "scan_id", "sha", "verdict", "ext", "filename")
"""Что можно подставить в имя объекта.

`filename` — имя исходного файла БЕЗ расширения, и это особая подстановка.
Остальные значения порождены нами: идентификаторы, хэши, вердикты, даты. Это —
единственное, что приходит **от пользователя**, то есть недоверенный ввод в
ключе объекта. Отсюда два следствия, и оба обязательны.

Первое: значение обезвреживается (`safe_filename`). Имя вида
`../../etc/passwd` или с переводом строки внутри — обычное дело для сервиса,
который считает весь вход враждебным.

Второе, и оно про приватность: чтобы подставить имя, его надо донести до
воркера через очередь, то есть **сохранить в Redis**, а Redis пишет на диск.
Имена документов часто содержат ФИО и номера, поэтому по умолчанию gateway
оставляет от имени только расширение. Подстановка включает хранение, и это
осознанный выбор тенанта, а не умолчание.
"""

_UNSAFE = re.compile(r'[\x00-\x1f\x7f/\\<>:"|?*]+')
_SPACES = re.compile(r"\s+")
MAX_FILENAME = 80
"""Ограничение длины. Ключ S3 целиком не длиннее 1024 байт, а имя — лишь его
часть: за ним ещё префикс, дата и расширение."""


def safe_filename(raw: str, fallback: str) -> str:
    """Имя пользователя, пригодное для ключа объекта.

    Убирается всё, что ломает путь или файловую систему получателя: разделители
    каталогов, управляющие символы и знаки, запрещённые в именах на Windows.
    Ящик забирают через `aws s3 sync`, и ключ становится именем файла на чужом
    диске — чем именно его читают, мы не знаем.

    Точки по краям срезаются отдельно: `...` — валидное имя в S3 и выход за
    каталог при выгрузке, а `.скрытый` на Unix прячет файл от `ls`.

    Пустой результат заменяется запасным значением: пустой сегмент в ключе
    отвергается, и без замены доставка встала бы на файле с именем `///`.
    """
    cleaned = _SPACES.sub(" ", _UNSAFE.sub("", raw)).strip(" .")
    return cleaned[:MAX_FILENAME].strip(" .") or fallback

_PLACEHOLDER = re.compile(r"\{([a-z_]*)\}")


def _safe_key(rendered: str) -> str:
    """Проверяет собранный ключ. Отказ — исключение, а не тихая правка.

    Ключ в S3 — не путь, и `..` для хранилища ничего не значит. Но клиент
    забирает ящик через `aws s3 sync`, и там ключ становится **именем файла на
    его диске**: сегмент `..` превращается в выход за каталог. Мы не знаем, чем
    ящик читают, поэтому не отдаём того, что может так прочитаться.
    """
    if rendered.startswith("/") or "\\" in rendered or "//" in rendered:
        raise DeliveryError(f"негодный ключ объекта: {rendered!r}")
    if any(part in ("", ".", "..") for part in rendered.split("/")):
        raise DeliveryError(f"негодный ключ объекта: {rendered!r}")
    return rendered


class DeliveryCredentials(BaseModel):
    """Чем аутентифицироваться в чужом хранилище. Живёт только у notifier."""

    model_config = ConfigDict(extra="forbid")

    access_key: str = Field(min_length=1)
    secret_key: str = Field(min_length=MIN_SECRET_LEN)

    def __repr__(self) -> str:
        """Секрет не должен попасть в лог через случайный `repr` объекта."""
        return f"DeliveryCredentials(access_key={self.access_key!r}, secret_key=<скрыт>)"

    __str__ = __repr__


class DeliveryError(ValueError):
    """Блок `delivery` есть, но разобрать его не удалось."""


def parse_delivery(payload: Any) -> Delivery:
    """Строгий разбор блока. Ошибка — исключение, а не `None`.

    Возврат `None` при неудаче означал бы «приёмника нет», а это другое
    состояние: приёмника нет — штатная работа, приёмник сломан — авария,
    которую надо чинить. Смешав их, мы получили бы молчаливую потерю доставки
    от одной опечатки.
    """
    if not isinstance(payload, dict):
        raise DeliveryError("ожидается объект с описанием приёмника")
    try:
        delivery = Delivery.model_validate(payload)
    except ValueError as exc:
        raise DeliveryError(str(exc)) from exc

    # Шаблон проверяется здесь, а не при первой выгрузке. Неизвестная
    # подстановка иначе всплыла бы на живом файле: `str.format` бросает
    # `KeyError`, доставка ушла бы в повторы и через десять попыток в
    # dead-letter — и всё это на конфигурации, негодной с самого начала.
    unknown = sorted(set(_PLACEHOLDER.findall(delivery.key_template)) - set(TOKENS))
    if unknown:
        raise DeliveryError(
            f"в key_template неизвестные подстановки: {unknown}; допустимы {list(TOKENS)}"
        )
    if "{" in _PLACEHOLDER.sub("", delivery.key_template):
        # Незакрытая скобка: `{scan_id{ext}` разберётся во что угодно, только
        # не в то, что имели в виду.
        raise DeliveryError(f"негодный key_template: {delivery.key_template!r}")

    # Прогоняем на образце: шаблон вроде `{date}//{scan_id}` собирается, но
    # даёт пустой сегмент, а `..` в ключе становится выходом за каталог у того,
    # кто заберёт ящик через `aws s3 sync`.
    delivery.object_name("проба", "0" * 64, "clean", ".pdf", 0.0)
    return delivery


class CredentialsRegistry:
    """Учётные данные приёмников. Читает только notifier.

    Устроен как `KeyRegistry` и по той же причине: файл с секретами не должен
    монтироваться туда, где он не нужен. Недоступный файл — это отказ
    доставки, а не работа без аутентификации.
    """

    def __init__(self, entries: dict[str, DeliveryCredentials], degraded: bool = False) -> None:
        self._entries = entries
        self.degraded = degraded
        """Файл задан, но не прочитан. Доставка при этом не выполняется вовсе:
        писать в чужое хранилище «как получится» нельзя."""

    def get(self, credentials_id: str) -> DeliveryCredentials | None:
        return self._entries.get(credentials_id)

    def __len__(self) -> int:
        return len(self._entries)

    @classmethod
    def load(cls, path: str | None) -> CredentialsRegistry:
        if not path:
            # Приёмников нет — обычное состояние установки, и жаловаться не на
            # что. Отсутствие доставки становится ошибкой только там, где
            # тенанту её настроили: см. `TenantPolicy.delivery`.
            return cls({})

        file = Path(path)
        if not file.is_file():
            logger.error(
                "файл учётных данных приёмников не найден, доставка отключена",
                extra={"path": str(file), "is_dir": file.is_dir()},
            )
            return cls({}, degraded=True)

        try:
            raw = json.loads(file.read_text())
        except Exception:
            logger.exception("файл учётных данных приёмников не читается")
            return cls({}, degraded=True)

        entries: dict[str, DeliveryCredentials] = {}
        for name, payload in raw.items():
            if name.startswith("_"):
                # Комментарии в JSON: тот же приём, что и в реестре ключей.
                continue
            try:
                entries[name] = DeliveryCredentials.model_validate(payload)
            except ValueError:
                # Одна негодная запись не закрывает доставку остальным. В лог
                # идёт имя, но не содержимое: тут секреты.
                logger.exception("негодная учётная запись приёмника", extra={"id": name})

        logger.info("учётные данные приёмников загружены", extra={"count": len(entries)})
        return cls(entries)
