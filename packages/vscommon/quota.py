"""Суточная квота на выдачу талонов (M12.5).

Зачем отдельно от ограничения частоты. Частота защищает сервис от всплеска:
она отвечает на вопрос «сколько запросов в секунду мы выдержим». Квота
защищает **владельца ключа** от счёта: она отвечает на вопрос «сколько это
будет стоить за сутки».

Шестьдесят запросов в минуту — это восемьдесят шесть тысяч файлов в день.
Публичный ключ виден каждому, кто открыл исходный код страницы, поэтому без
суточного потолка он превращается либо в бесплатный антивирус за чужой счёт,
либо в способ разорить владельца. Ограничение частоты этого не ловит: поток
внутри лимита выглядит совершенно штатным.

Счётчик суточный и по календарным суткам UTC, а не скользящий. Скользящее окно
точнее, но требует хранить отметки каждого события; здесь это тысячи записей
на ключ ради того, чтобы граница проходила ровнее. Календарные сутки понятны
владельцу ключа — он видит их в счёте, — и стоят одного числа в Redis.
"""

from __future__ import annotations

import logging
from datetime import UTC, datetime
from typing import Any

logger = logging.getLogger(__name__)

DAY_S = 86_400


class DailyQuota:
    """Счётчик израсходованного за сутки.

    Ключ включает дату, поэтому новые сутки начинаются с чистого счётчика сами
    собой — обнулять ничего не надо. TTL стоит на всякий случай: без него
    записи копились бы вечно, а читать их некому.
    """

    def __init__(self, redis: Any, prefix: str = "quota") -> None:
        self._redis = redis
        self._prefix = prefix

    @staticmethod
    def _today() -> str:
        return datetime.now(UTC).strftime("%Y-%m-%d")

    def _key(self, subject: str) -> str:
        return f"{self._prefix}:{self._today()}:{subject}"

    async def spend(self, subject: str, limit: int, amount: int = 1) -> bool:
        """Тратит `amount` единиц. Возвращает, уложились ли в лимит.

        Инкремент идёт ДО сравнения и не откатывается при отказе. Это
        осознанно: откат означал бы «прочитать, сравнить, записать», то есть
        гонку, в которой два параллельных запроса пробивают лимит. Пусть лучше
        отказанная попытка тоже считается — она такой же расход на нашей
        стороне, и злоупотребление ею не выгоднее, чем успешная загрузка.
        """
        if limit <= 0:
            # Ноль означает «без счёта», как и у остальных лимитов тенанта.
            return True

        key = self._key(subject)
        try:
            spent = int(await self._redis.incrby(key, amount))
            if spent == amount:
                # Первый расход в этих сутках — ставим срок жизни. Отдельным
                # вызовом, а не при каждом инкременте: продлевать TTL на каждом
                # запросе значит никогда его не дождаться.
                await self._redis.expire(key, DAY_S * 2)
        except Exception:
            # Redis недоступен. Отказывать в загрузке из-за счётчика нельзя:
            # это превратило бы вспомогательный механизм в единственную точку
            # отказа. Проверка файла важнее учёта.
            logger.exception("не удалось учесть расход квоты, пропускаю")
            return True

        return spent <= limit

    async def spent(self, subject: str) -> int:
        """Сколько израсходовано за сегодня. Для диагностики и метрик."""
        raw = await self._redis.get(self._key(subject))
        return int(raw) if raw else 0
