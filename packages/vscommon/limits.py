"""Лимиты защиты от бомб и переполнения. Единственный источник правды."""

from __future__ import annotations

from typing import Final

MAX_UPLOAD_BYTES: Final[int] = 64 * 1024 * 1024
"""Больше этого не принимаем на вход вовсе."""

MAX_SANITIZED_BYTES: Final[int] = 128 * 1024 * 1024
"""Выход CDR не может быть больше — защита от декомпресс-бомбы на выходе."""

MAX_IMAGE_PIXELS: Final[int] = 80_000_000
"""~80 Мпикс. Дальше Pillow должен отказать, а не аллоцировать гигабайты."""

MAX_PDF_PAGES: Final[int] = 500
MAX_PDF_OBJECTS: Final[int] = 200_000
MAX_PDF_NESTING_DEPTH: Final[int] = 128
"""Порог признака, а не защита.

Защита — итеративный обход с лимитом шагов, ему глубина не вредит. Порог
подобран по реальным документам: медиана 2, p99 = 49. Прежние 32 задевали
обычные многостраничные PDF со вложенными формами.
"""

STAGE_TIMEOUT_S: Final[dict[str, float]] = {
    "filetype": 2.0,
    "structure": 10.0,
    "clamav": 20.0,
    "yara": 10.0,
}

CDR_TIMEOUT_S: Final[dict[str, float]] = {
    "light": 15.0,
    "standard": 60.0,
    "strict": 180.0,
}

# --- архивы и контейнеры (M6) ---
#
# Бюджет общий на всё дерево вложенности, а не на каждый архив. Классическая
# бомба (42.zip) на каждом уровне выглядит безобидно — шестнадцать файлов по
# 30 КБ — и разворачивается в петабайты только целиком. Лимит на архив она
# проходит по построению.

MAX_UNPACKED_BYTES: Final[int] = 256 * 1024 * 1024
"""Сколько байт распаковывается из одного загруженного файла суммарно.

Распаковка идёт в tmpfs, то есть в память воркера. Четыре загрузки по
максимуму — и больше этого держать в памяти одновременно нельзя.
"""

MAX_ARCHIVE_MEMBER_BYTES: Final[int] = MAX_UPLOAD_BYTES
"""Больше этого вложение не распаковывается: снаружи такой файл не приняли бы."""

MAX_ARCHIVE_ENTRIES: Final[int] = 500
"""Записей во всём дереве. Каждая — полный проход стадий, включая антивирус."""

MAX_ARCHIVE_DEPTH: Final[int] = 4
"""Архив в архиве: корень — уровень 0. Глубже не распаковываем.

Заодно ограничивает архив-квайн, содержащий сам себя: без предела глубины он
разворачивается бесконечно при конечном размере.
"""

ARCHIVE_BOMB_RATIO: Final[int] = 100
"""Во сколько раз распакованное больше загруженного, чтобы превышение бюджета
считалось бомбой, а не просто большим архивом.

Документы и сканы сжимаются в разы, а не в сотни раз: deflate на нулях даёт
около 1000, на тексте — 3-10. Превышение бюджета при коэффициенте ниже этого
— просто объём, который мы не взялись проверить (вердикт `unsupported`).
"""

ARCHIVE_TIME_BUDGET_S: Final[float] = 120.0
"""Время на проверку всех вложений вместе.

Таймауты стадий действуют на каждое вложение отдельно, и пятьсот записей по
двадцать секунд антивируса — это почти три часа на один файл.
"""

MAX_OOXML_PART_BYTES: Final[int] = 32 * 1024 * 1024
"""Больше этого XML-часть документа Word не разбирается в дерево.

Дерево элементов занимает в памяти в разы больше исходного текста.
"""
